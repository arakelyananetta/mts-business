/* ответ всегда объект: { text, cta } — cta ведёт в раздел одной кнопкой */
export function answerQuery(text) {
  const q = text.toLowerCase()
  const A_CTA = { label: 'Открыть аналитику', to: 'analytics' }
  if (/свод|итог|кратк/.test(q)) {
    if (q.includes('недел')) return { text: SUMMARIES.week, cta: A_CTA }
    if (q.includes('квартал')) return { text: SUMMARIES.quarter, cta: A_CTA }
    if (q.includes('месяц') || q.includes('июл')) return { text: SUMMARIES.month, cta: A_CTA }
    return { text: 'Могу подготовить краткую сводку результатов бизнеса. За какой период — неделя, месяц или квартал? Напишите, например: «сводка за месяц».', cta: null }
  }
  const hit = ANSWERS.find(([keys]) => keys.some((k) => q.includes(k)))
  if (hit) return { text: hit[1], cta: hit[2] || null }
  return { text: FALLBACK, cta: null }
}

